/// Renders the generated Dart library.
String generateDart({
  required GenClass root,
  required List<GenClass> classes,
  required KumaConfig config,
  required String fingerprint,
}) {
  final out = StringBuffer()
    ..writeln('// GENERATED by kuma — do not edit.')
    ..writeln('// kuma-fingerprint: $fingerprint')
    ..writeln('// ignore_for_file: type=lint')
    ..writeln()
    ..writeln(
      "import 'package:easy_localization/easy_localization.dart' as el;",
    );
  if (config.contextExtension) {
    out.writeln("import 'package:flutter/widgets.dart';");
  }
  for (final ns in config.namespaces) {
    out.writeln("import '${ns.import}' as ${_nsPrefix(ns)};");
  }
  out.writeln();

  for (final cls in classes) {
    _writeClass(out, cls, isRoot: identical(cls, root), config: config);
  }

  if (config.contextExtension) {
    out
      ..writeln('extension ${config.className}ContextX on BuildContext {')
      ..writeln('  /// Translations for widgets. Reading this subscribes the')
      ..writeln(
          '  /// widget to locale changes, so it rebuilds on `setLocale`.')
      ..writeln('  ${config.className} get ${config.contextGetter} {')
      ..writeln('    el.EasyLocalization.of(this);')
      ..writeln('    return ${config.className}.instance;')
      ..writeln('  }')
      ..writeln('}');
  }

  return DartFormatter(
    languageVersion: DartFormatter.latestLanguageVersion,
  ).format(out.toString());
}

void _writeClass(
  StringBuffer out,
  GenClass cls, {
  required bool isRoot,
  required KumaConfig config,
}) {
  out.writeln('class ${cls.name} {');
  out.writeln('  const ${cls.name}._();');
  if (isRoot) {
    out.writeln();
    if (config.contextExtension) {
      out
        ..writeln('  /// For code outside the widget tree. Widgets should use')
        ..writeln('  /// `context.${config.contextGetter}` so they rebuild on '
            'locale change.');
    }
    out.writeln('  static const instance = ${cls.name}._();');
  }
  for (final member in cls.members) {
    out.writeln();
    switch (member) {
      case GenPackageNamespace(:final config):
        final type = '${_nsPrefix(config)}.${config.className}';
        out
          ..writeln('  /// Keys from `package:${config.package}`.')
          ..writeln('  $type get ${member.dartName} => $type.instance;');
      case GenNamespace(:final cls):
        out.writeln(
          '  ${cls.name} get ${member.dartName} => const ${cls.name}._();',
        );
      case GenLeaf():
        _writeDoc(out, member.node);
        out.writeln('  ${_leaf(member, config)}');
    }
  }
  out
    ..writeln('}')
    ..writeln();
}

String _leaf(GenLeaf leaf, KumaConfig config) {
  final key = _literal(
    config.keyPrefix == null
        ? leaf.node.path
        : '${config.keyPrefix}.${leaf.node.path}',
  );
  switch (leaf.signature) {
    case final MessageSignature sig:
      if (sig.isGetter) return 'String get ${leaf.dartName} => el.tr($key);';
      final params = _params(positional: sig.positional, named: sig.named);
      final args = [key, ..._callArgs(sig)];
      return 'String ${leaf.dartName}($params) => el.tr(${args.join(', ')});';
    case final PluralSignature sig:
      final params = _params(
        leading: ['num ${sig.countParam}'],
        positional: sig.positional,
        named: sig.named,
        optional: [
          if (sig.formatParam != null) 'el.NumberFormat? ${sig.formatParam}',
        ],
      );
      final args = [
        key,
        sig.countParam,
        if (sig.countMode == CountMode.named)
          "name: ${_literal(sig.countName!)}",
        ..._callArgs(sig),
        if (sig.formatParam != null) 'format: ${sig.formatParam}',
      ];
      return 'String ${leaf.dartName}($params) => '
          'el.plural(${args.join(', ')});';
  }
}

/// `args:` and `namedArgs:`. `args` is never passed empty: easy_localization
/// treats `[]` as "arguments given" and stops filling `{}` with the count.
List<String> _callArgs(Signature sig) => [
      if (sig.positional.isNotEmpty)
        'args: [${sig.positional.map((p) => p.dartName).join(', ')}]',
      if (sig.named.isNotEmpty)
        'namedArgs: {${sig.named.map((p) => '${_literal(p.placeholder!)}: ${p.dartName}').join(', ')}}',
    ];

String _params({
  List<String> leading = const [],
  required List<Param> positional,
  required List<Param> named,
  List<String> optional = const [],
}) {
  final required = [
    ...leading,
    ...positional.map((p) => 'String ${p.dartName}'),
  ];
  final namedParts = [
    ...named.map((p) => 'required String ${p.dartName}'),
    ...optional,
  ];
  return [
    ...required,
    if (namedParts.isNotEmpty) '{${namedParts.join(', ')}}',
  ].join(', ');
}

void _writeDoc(StringBuffer out, L10nNode node) {
  final lines = <String>[];
  switch (node) {
    case MessageNode(:final text):
      lines.addAll(text.split('\n'));
    case PluralNode(:final forms):
      for (final MapEntry(:key, :value) in forms.entries) {
        final textLines = value.split('\n');
        lines.add('$key: ${textLines.first}');
        lines.addAll(textLines.skip(1).map((l) => '  $l'));
      }
    case NamespaceNode():
      return;
  }
  for (final line in lines) {
    out.writeln('  /// ${line.replaceAll('\r', '')}'.trimRight());
  }
}

String _nsPrefix(NamespaceConfig ns) => 'kuma_${ns.name}';

String _literal(String value) {
  final escaped = value
      .replaceAll(r'\', r'\\')
      .replaceAll("'", r"\'")
      .replaceAll(r'$', r'\$')
      .replaceAll('\n', r'\n')
      .replaceAll('\r', r'\r');
  return "'$escaped'";
}
